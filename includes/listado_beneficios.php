<script>
    document.addEventListener('DOMContentLoaded', function () {
        var categorias_beneficios = <?php echo json_encode($categorias_beneficios); ?>;

        var modulo_beneficios = document.querySelector('.swiss-benefits-module');
        if (!modulo_beneficios) return;

        var botones_categorias = modulo_beneficios.querySelectorAll('.swiss-category-btn');
        var contenedor_beneficios = modulo_beneficios.querySelector('#swiss_benefits_container');

        function escapar_html(texto) {
            return String(texto == null ? '' : texto)
                .replace(/&/g, '&amp;')
                .replace(/</g, '&lt;')
                .replace(/>/g, '&gt;')
                .replace(/"/g, '&quot;')
                .replace(/'/g, '&#039;');
        }

        function obtener_inicial(titulo) {
            var texto = String(titulo == null ? '' : titulo).trim();
            return texto ? texto.charAt(0).toUpperCase() : 'B';
        }

        function resumir_descripcion(texto, limite_palabras) {
            var palabras = String(texto == null ? '' : texto)
                .replace(/\s+/g, ' ')
                .trim()
                .split(' ');

            if (!palabras.length || palabras[0] === '') return '';
            if (palabras.length <= limite_palabras) return palabras.join(' ');

            return palabras.slice(0, limite_palabras).join(' ') + '...';
        }

        function renderizar_beneficios(indice_categoria) {
            var categoria_actual = categorias_beneficios[indice_categoria];
            if (!categoria_actual || !categoria_actual.beneficios) return;

            contenedor_beneficios.innerHTML = '';
            contenedor_beneficios.classList.remove('swiss-fade');
            void contenedor_beneficios.offsetWidth;
            contenedor_beneficios.classList.add('swiss-fade');

            categoria_actual.beneficios.forEach(function (beneficio) {
                var titulo = escapar_html(beneficio.titulo);
                var descripcion = escapar_html(resumir_descripcion(beneficio.descripcion, 22));
                var enlace = escapar_html(String(beneficio.enlace == null ? '#' : beneficio.enlace).trim());

                var logoHtml = beneficio.logo
                    ? '<img src="' + escapar_html(beneficio.logo) + '" alt="Logo de ' + titulo + '" class="swiss-benefit-logo" loading="lazy">'
                    : '<span class="swiss-benefit-logo-placeholder" aria-hidden="true">' + obtener_inicial(beneficio.titulo) + '</span>';

                var tarjeta = document.createElement('article');
                tarjeta.className = 'swiss-benefit-card';
                tarjeta.innerHTML =
                    '<div class="swiss-benefit-image-wrapper">' +
                        '<div class="swiss-benefit-image-bg" aria-hidden="true"></div>' +
                        logoHtml +
                    '</div>' +
                    '<div class="swiss-benefit-card-body">' +
                        '<h2 class="swiss-benefit-title">' + titulo + '</h2>' +
                        '<p class="swiss-benefit-description">' + descripcion + '</p>' +
                        '<a class="boton-sm swiss-benefit-action" href="' + enlace + '" target="_blank" rel="noopener noreferrer">Ver beneficio</a>' +
                    '</div>';

                contenedor_beneficios.appendChild(tarjeta);
            });
        }

        Array.prototype.forEach.call(botones_categorias, function (boton_categoria) {
            boton_categoria.addEventListener('click', function (evento) {
                Array.prototype.forEach.call(botones_categorias, function (boton) {
                    boton.classList.remove('is-active');
                    boton.setAttribute('aria-selected', 'false');
                });

                evento.currentTarget.classList.add('is-active');
                evento.currentTarget.setAttribute('aria-selected', 'true');

                var indice_categoria = parseInt(evento.currentTarget.getAttribute('data-index'), 10);
